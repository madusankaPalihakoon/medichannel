CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          appointment_id BIGINT NOT NULL UNIQUE
                              REFERENCES appointments(id)
                                  ON UPDATE CASCADE ON DELETE RESTRICT,

                          amount NUMERIC(12,2) NOT NULL
                              CHECK (amount >= 0),

                          payment_method VARCHAR(10)
                              CHECK (payment_method IN ('CASH','CARD')),

                          payment_status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                              CHECK (payment_status IN ('PENDING','PAID')),

                          paid_at TIMESTAMPTZ,

                          recorded_by BIGINT
                              REFERENCES users(id)
                                  ON UPDATE CASCADE ON DELETE RESTRICT,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_payment_details
                              CHECK (
                                  (
                                      payment_status = 'PENDING'
                                          AND paid_at IS NULL
                                      )
                                      OR
                                  (
                                      payment_status = 'PAID'
                                          AND paid_at IS NOT NULL
                                          AND payment_method IS NOT NULL
                                      )
                                  )
);

CREATE INDEX idx_payments_status_created
    ON payments(payment_status, created_at DESC);

-- =============================================================
-- 9. CONSULTATIONS
-- =============================================================

CREATE TABLE consultations (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               appointment_id BIGINT NOT NULL UNIQUE
                                   REFERENCES appointments(id)
                                       ON UPDATE CASCADE ON DELETE RESTRICT,

                               diagnosis_summary_encrypted TEXT,
                               advice_encrypted TEXT,
                               prescription_encrypted TEXT,
                               consultation_notes_encrypted TEXT,

                               started_at TIMESTAMPTZ,
                               completed_at TIMESTAMPTZ,

                               CONSTRAINT chk_consultation_time
                                   CHECK (
                                       completed_at IS NULL

-- =============================================================
-- 1. USERS
-- =============================================================

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name_ciphertext TEXT NOT NULL,
                       email_ciphertext TEXT NOT NULL,
                       email_lookup_hash VARCHAR(64) NOT NULL UNIQUE
                           CHECK (email_lookup_hash ~ '^[0-9a-f]{64}$'),
                       password_hash VARCHAR(100) NOT NULL,
                       role VARCHAR(20) NOT NULL
                           CHECK (role IN ('ADMIN','MANAGER','DOCTOR','CUSTOMER')),
                       active BOOLEAN NOT NULL DEFAULT TRUE,
                       failed_login_attempts INTEGER NOT NULL DEFAULT 0
                           CHECK (failed_login_attempts BETWEEN 0 AND 5),
                       locked_until TIMESTAMPTZ,
                       password_change_required BOOLEAN NOT NULL DEFAULT FALSE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role_active
    ON users(role, active);

-- =============================================================
-- 2. PATIENTS
-- =============================================================

CREATE TABLE patients (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id BIGINT NOT NULL UNIQUE
                              REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
                          nic_ciphertext TEXT NOT NULL,
                          nic_lookup_hash VARCHAR(64) NOT NULL UNIQUE
                              CHECK (nic_lookup_hash ~ '^[0-9a-f]{64}$'),
                          date_of_birth_ciphertext TEXT NOT NULL,
                          gender VARCHAR(20),
                          phone_ciphertext TEXT NOT NULL,
                          address_ciphertext TEXT NOT NULL,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_patient_gender
                              CHECK (
                                  gender IS NULL OR
                                  gender IN ('MALE','FEMALE','OTHER','PREFER_NOT_TO_SAY')
                                  )
);

-- =============================================================
-- 3. SPECIALISATIONS
-- =============================================================

CREATE TABLE specialisations (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 name VARCHAR(100) NOT NULL UNIQUE,
                                 description TEXT,
                                 is_active BOOLEAN NOT NULL DEFAULT TRUE,
                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================
-- 4. DOCTORS
-- =============================================================

CREATE TABLE doctors (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL UNIQUE
                             REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
                         specialisation_id BIGINT NOT NULL
                             REFERENCES specialisations(id)
                                 ON UPDATE CASCADE ON DELETE RESTRICT,
                         slmc_number VARCHAR(30) NOT NULL UNIQUE,
                         qualifications TEXT NOT NULL,
                         experience_years INTEGER NOT NULL DEFAULT 0

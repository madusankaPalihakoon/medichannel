                         consultation_fee NUMERIC(12,2) NOT NULL
                             CHECK (consultation_fee >= 0),
                         bio TEXT,
                         is_active BOOLEAN NOT NULL DEFAULT TRUE,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_doctors_specialisation_active
    ON doctors(specialisation_id, is_active);

-- =============================================================
-- 5. ROOMS
-- =============================================================

CREATE TABLE rooms (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       room_name VARCHAR(100) NOT NULL UNIQUE,
                       location VARCHAR(150),
                       is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- =============================================================
-- 6. SESSIONS
-- =============================================================

CREATE TABLE sessions (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          doctor_id BIGINT NOT NULL
                              REFERENCES doctors(id)
                                  ON UPDATE CASCADE ON DELETE RESTRICT,

                          room_id BIGINT
                              REFERENCES rooms(id)
                                  ON UPDATE CASCADE ON DELETE RESTRICT,

                          session_date DATE NOT NULL,
                          start_time TIME WITHOUT TIME ZONE NOT NULL,
                          end_time TIME WITHOUT TIME ZONE NOT NULL,

                          session_type VARCHAR(10) NOT NULL
                              CHECK (session_type IN ('PHYSICAL','ONLINE')),

                          max_patients INTEGER NOT NULL
                              CHECK (max_patients BETWEEN 1 AND 60),

                          minutes_per_patient INTEGER NOT NULL
                              CHECK (minutes_per_patient BETWEEN 5 AND 30),

                          delay_minutes INTEGER NOT NULL DEFAULT 0
                              CHECK (delay_minutes >= 0),

                          consultation_fee NUMERIC(12,2) NOT NULL
                              CHECK (consultation_fee >= 0),

                          status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                              CHECK (
                                  status IN (
                                             'SCHEDULED',
                                             'OPEN',
                                             'IN_PROGRESS',
                                             'COMPLETED',
                                             'CANCELLED'
                                      )
                                  ),

                          next_appointment_number INTEGER NOT NULL DEFAULT 1,
                          now_serving_number INTEGER NOT NULL DEFAULT 0,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_session_time
                              CHECK (end_time > start_time),

                          CONSTRAINT chk_session_room_type
                              CHECK (
                                  (session_type = 'PHYSICAL' AND room_id IS NOT NULL)
                                      OR
                                  (session_type = 'ONLINE' AND room_id IS NULL)
                                  ),

                          CONSTRAINT chk_session_counter
                              CHECK (
                                  next_appointment_number BETWEEN 1 AND max_patients + 1
                                  ),

                          CONSTRAINT chk_now_serving
                              CHECK (
                                  now_serving_number BETWEEN 0 AND max_patients
                                  ),

    -- Prevent overlapping sessions for the same doctor.
                          CONSTRAINT ex_doctor_session_overlap
                              EXCLUDE USING gist (
                              doctor_id WITH =,
                              tsrange(
                                      session_date + start_time,
                                      session_date + end_time,
                                      '[)'
                              ) WITH &&
                              )
                              WHERE (status <> 'CANCELLED'),

    -- Prevent overlapping bookings for the same physical room.
                          CONSTRAINT ex_room_session_overlap
                              EXCLUDE USING gist (
                              room_id WITH =,
                              tsrange(
                                      session_date + start_time,
                                      session_date + end_time,
                                      '[)'
                              ) WITH &&
                              )
                              WHERE (
                                  room_id IS NOT NULL
                                      AND status <> 'CANCELLED'
                                  )
);

CREATE INDEX idx_sessions_doctor_date
    ON sessions(doctor_id, session_date);

CREATE INDEX idx_sessions_date_status
    ON sessions(session_date, status);

CREATE INDEX idx_sessions_type_date
    ON sessions(session_type, session_date);


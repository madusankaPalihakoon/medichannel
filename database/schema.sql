-- =============================================================
-- AUDIT LOG IMMUTABILITY
-- =============================================================

CREATE OR REPLACE FUNCTION medichannel_prevent_audit_mutation()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'Audit log records are immutable'
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER trg_audit_logs_immutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW
EXECUTE FUNCTION medichannel_prevent_audit_mutation();


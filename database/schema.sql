-- 7. APPOINTMENTS
-- =============================================================

CREATE TABLE appointments (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              session_id BIGINT NOT NULL
                                  REFERENCES sessions(id)
                                      ON UPDATE CASCADE ON DELETE RESTRICT,

                              patient_id BIGINT NOT NULL
                                  REFERENCES patients(id)
                                      ON UPDATE CASCADE ON DELETE RESTRICT,

                              appointment_number INTEGER NOT NULL
                                  CHECK (appointment_number >= 1),

                              reason_for_visit_ciphertext TEXT NOT NULL,

                              appointment_status VARCHAR(25) NOT NULL DEFAULT 'BOOKED'
                                  CHECK (
                                      appointment_status IN (
                                                             'BOOKED',
                                                             'ARRIVED',
                                                             'IN_CONSULTATION',
                                                             'COMPLETED',
                                                             'CANCELLED',
                                                             'NO_SHOW'
                                          )
                                      ),

                              payment_status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                                  CHECK (payment_status IN ('PENDING','PAID')),

                              payment_method VARCHAR(10)
                                  CHECK (payment_method IN ('CASH','CARD')),

                              booked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              arrived_at TIMESTAMPTZ,
                              cancelled_at TIMESTAMPTZ,
                              estimated_at TIMESTAMPTZ,

                              CONSTRAINT uq_appointment_session_number
                                  UNIQUE (session_id, appointment_number),

    -- FIX: Required for the FEEDBACK composite foreign key.
                              CONSTRAINT uq_appointment_id_patient
                                  UNIQUE (id, patient_id),

                              CONSTRAINT chk_appointment_payment
                                  CHECK (
                                      payment_status <> 'PAID'
                                          OR payment_method IS NOT NULL
                                      ),

                              CONSTRAINT chk_appointment_cancelled_time
                                  CHECK (
                                      (
                                          appointment_status = 'CANCELLED'
                                              AND cancelled_at IS NOT NULL
                                          )
                                          OR
                                      (
                                          appointment_status <> 'CANCELLED'
                                              AND cancelled_at IS NULL
                                          )
                                      )
);

CREATE INDEX idx_appointments_session_status
    ON appointments(
                    session_id,
                    appointment_status,
                    appointment_number
        );

CREATE INDEX idx_appointments_patient_booked
    ON appointments(patient_id, booked_at DESC);

CREATE INDEX idx_appointments_status
    ON appointments(appointment_status);


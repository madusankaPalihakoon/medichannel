CREATE UNIQUE INDEX uq_active_patient_session
    ON appointments(session_id, patient_id)
    WHERE appointment_status IN (
                                 'BOOKED',
                                 'ARRIVED',
                                 'IN_CONSULTATION'
        );

-- =============================================================
-- APPOINTMENT CAPACITY VALIDATION
-- =============================================================

CREATE OR REPLACE FUNCTION medichannel_check_appointment_number()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
DECLARE
    session_capacity INTEGER;
BEGIN
    SELECT max_patients
    INTO session_capacity
    FROM sessions
    WHERE id = NEW.session_id;

    IF session_capacity IS NULL THEN
        RAISE EXCEPTION
            'Session % does not exist', NEW.session_id
            USING ERRCODE = '23503';
    END IF;

    IF NEW.appointment_number > session_capacity THEN
        RAISE EXCEPTION
            'Appointment number exceeds session capacity'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_check_appointment_number
    BEFORE INSERT OR UPDATE OF session_id, appointment_number
    ON appointments
    FOR EACH ROW
EXECUTE FUNCTION medichannel_check_appointment_number();

